# ## Configuration check

# %%
def print_json(title: str, payload: dict[str, Any]) -> None:
    print(f"\n## {title}")
    print(json.dumps(payload, indent=2, sort_keys=True))


paths = ExperimentPaths()
config = load_config()
experiment = get_nested(config, "experiment") or {}
inference = get_nested(config, "inference") or {}
print_json(
    "inference status",
    {
        "experiment": experiment.get("name"),
        "route": experiment.get("route"),
        "inference_enabled": experiment.get("inference_enabled"),
        "mode": inference.get("mode"),
        "notes": inference.get("notes"),
    },
)
if bool(experiment.get("inference_enabled", False)) or inference.get("mode") != "disabled_diagnostic_only":
    raise RuntimeError("exp236 must remain train-side diagnostic only")
print("No inference or submission artifact is generated by design.")
